import fs from 'node:fs';
import assert from 'node:assert/strict';
const worker=fs.readFileSync('cloudflare/worker.js','utf8');
const tenantUi=fs.readFileSync('frontend/assets/js/tenant-admin.js','utf8');
const accountUi=fs.readFileSync('frontend/assets/js/account.js','utf8');
const shareUi=fs.readFileSync('frontend/assets/js/tenant-share.js','utf8');
const assistant=fs.readFileSync('frontend/assets/js/assistant.js','utf8');
const from=worker.indexOf('async function tenantFromSession(r,e){');
const to=worker.indexOf('\n\nasync function tenantSettings',from);
assert(from>=0&&to>from,'tenantFromSession must exist');
const auth=worker.slice(from,to);
assert(auth.includes("String(x.slug||'').toLowerCase()===requestedSlug"),'session resolver must prefer exact tenant slug');
assert(auth.includes('const buyer=await buyerFromRequest(r,e)'),'stale tenant session must still try verified buyer-owner fallback');
assert(auth.includes('owner_user_id=?'),'owner identity must be checked, not just slug');
assert(auth.includes('Number(buyer.email_verified)===1?1:0'),'email-based SSO must require verified buyer email');
assert(worker.includes('linkedBuyerSession:!!linkedBuyer'),'tenant login must report whether the buyer session was safely linked');
assert(worker.includes("INSERT INTO buyer_sessions(token,buyer_id,expires_at) VALUES(?,?,?) ON CONFLICT(token) DO UPDATE"),'linked tenant login token must be shared with buyer APIs');
assert(tenantUi.includes("localStorage.setItem('TEO_BUYER_SESSION',token)"),'tenant UI must persist shared buyer session');
assert(tenantUi.includes("storedSlug!==requested"),'tenant UI must discard a tenant token belonging to another Studio');
assert(accountUi.includes("localStorage.removeItem('TEO_TENANT_SESSION')"),'switching buyer identity must clear stale tenant session');
assert(shareUi.includes("localStorage.getItem('TEO_BUYER_SESSION')"),'Share comments must use shared buyer identity');
assert(assistant.includes("localStorage.getItem('TEO_TENANT_SESSION')"),'AI must use authenticated tenant context');
assert(!/u\.pathname\s*=\s*['"]\/share\.html['"]/.test(worker),'Worker must not rewrite /share to /share.html');
console.log('PASS unified tenant session static checks: exact slug resolution, verified owner SSO, account switching, Share comments, AI context and no Share rewrite.');
