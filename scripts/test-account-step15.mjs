import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('frontend/account.html','utf8');
const js=fs.readFileSync('frontend/assets/js/account.js','utf8');
const css=fs.readFileSync('frontend/assets/css/page-account.css','utf8');
assert.match(html,/assets\/css\/tokens\.css\?v=60\.3/,'account loads design tokens');
assert.match(html,/assets\/css\/page-account\.css\?v=60\.3/,'account loads page-specific stylesheet');
assert.match(html,/data-role="buyer"/,'account declares buyer role');
assert.match(html,/id="teoAccountMount"/,'account mount remains present');
assert.match(js,/function showAccountLoadError\(err\)/,'account has recoverable API error view');
assert.match(js,/const expired=status===401\|\|code==='ACCOUNT_REQUIRED'/,'only expired/invalid session triggers login reset');
assert.match(js,/catch\(err\)\{showAccountLoadError\(err\)\}/,'profile API errors are surfaced without unconditional logout');
assert.match(js,/\.catch\(err=>showAccountLoadError\(err\)\)/,'initial account bootstrap preserves session on server errors');
assert.match(js,/id="teoAccountRetry"/,'error view offers retry');
assert.match(css,/overflow-x:clip/,'account page clips horizontal overflow');
assert.match(css,/min-width:0/,'account layout uses shrink-safe min widths');
assert.match(css,/--accent/,'account uses design tokens');
assert.doesNotMatch(css,/#[0-9a-f]{6}\b/i,'account CSS has no hardcoded hex colors');
console.log('PASS Step 1.5 account: token wiring, buyer role, responsive guards, retry path, and session preservation on server errors.');
