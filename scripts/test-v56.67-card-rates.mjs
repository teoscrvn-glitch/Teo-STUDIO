import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync(new URL('../cloudflare/worker.js', import.meta.url), 'utf8');
const start = source.indexOf('const CARD_DENOMINATIONS=');
const end = source.indexOf('\nasync function getCardRateConfig', start);
if (start < 0 || end < 0) throw new Error('Card tariff normalizer not found');
const sandbox = {};
vm.runInNewContext(source.slice(start, end) + '\nthis.__test={defaultCardRateConfig,normalizeCardRateConfig,CARD_DENOMINATIONS};', sandbox);
const { normalizeCardRateConfig, CARD_DENOMINATIONS } = sandbox.__test;
const defaults = normalizeCardRateConfig({});
if (defaults.providers.vinaphone.rates['10000'].partner !== 17.1) throw new Error('Partner 10k tariff mismatch');
if (defaults.providers.vinaphone.rates['10000'].member !== 17.3) throw new Error('Member 10k tariff mismatch');
if (Math.floor(10000 * (1 - 17.3 / 100) / 1000) * 1000 !== 8000) throw new Error('Expected wallet credit rounding mismatch');
const incomplete = { providers: { vinaphone: { enabled: true, rates: { '10000': { partner: 17.1, member: null } } } } };
const blocked = normalizeCardRateConfig(incomplete).providers.vinaphone;
if (blocked.enabled || blocked.rates['10000'].member !== null) throw new Error('Incomplete tariff incorrectly enabled or coerced to 0%');
const full = { providers: { vinaphone: { enabled: true, rates: {} } } };
for (const amount of CARD_DENOMINATIONS) full.providers.vinaphone.rates[String(amount)] = { partner: 17.1, member: 17.3 };
if (!normalizeCardRateConfig(full).providers.vinaphone.enabled) throw new Error('Complete tariff was not enabled');
console.log('PASS V56.67 card tariff normalization and 1,000 VND floor rounding.');
